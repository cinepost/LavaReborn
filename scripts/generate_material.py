#!/usr/bin/env python3
"""Generate the stable native material IR and its pass-specific GLSL bindings.
MaterialX graph lowering can target this IR without involving accumulation.
"""
from pathlib import Path
fields = {
 'base_weight':1., 'base_color':(.8,.8,.8), 'base_diffuse_roughness':0., 'base_metalness':0.,
 'specular_weight':1., 'specular_color':(1.,1.,1.), 'specular_roughness':.3,
 'specular_roughness_anisotropy':0., 'specular_ior':1.5,
 'coat_weight':0., 'coat_color':(1.,1.,1.), 'coat_roughness':0.,
 'coat_roughness_anisotropy':0., 'coat_ior':1.6, 'coat_darkening':1.,
 'fuzz_weight':0., 'fuzz_color':(1.,1.,1.), 'fuzz_roughness':.5,
 'transmission_weight':0., 'transmission_color':(1.,1.,1.), 'transmission_depth':0.,
 'transmission_scatter':(0.,0.,0.), 'transmission_scatter_anisotropy':0.,
 'transmission_dispersion_scale':0., 'transmission_dispersion_abbe_number':20.,
 'thin_film_weight':0., 'thin_film_thickness':.5, 'thin_film_ior':1.4,
 'emission_luminance':0., 'emission_color':(1.,1.,1.),
 'geometry_opacity':1., 'geometry_thin_walled':False,
 'subsurface_weight':0., 'subsurface_color':(.8,.8,.8), 'subsurface_radius':1.,
 'subsurface_radius_scale':(1.,.5,.25), 'subsurface_scatter_anisotropy':0.,
}
def val(v):
 if isinstance(v,tuple):return '['+', '.join(map(str,v))+']'
 if isinstance(v,bool):return str(v).lower()
 return str(v)
s='// Generated by scripts/generate_material.py.\nuse serde::{Serialize, Deserialize};\n#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]\n#[serde(default, deny_unknown_fields)]\npub struct OpenPbrSurface {\n'
for k,v in fields.items():s+=f'    pub {k}: '+('[f32; 3]' if isinstance(v,tuple) else 'bool' if isinstance(v,bool) else 'f32')+',\n'
s+='}\nimpl Default for OpenPbrSurface { fn default() -> Self { Self {\n'
for k,v in fields.items():s+=f'    {k}: {val(v)},\n'
s+='} } }\nimpl OpenPbrSurface {\n pub fn gpu(&self) -> GpuMaterial { GpuMaterial { values: [\n [1., 0., 0., 0.],\n'
for k,v in fields.items():
 x=f'self.{k}'
 s+=' '+(f'[{x}[0], {x}[1], {x}[2], 0.]' if isinstance(v,tuple) else f'[{x} as u8 as f32, 0., 0., 0.]' if isinstance(v,bool) else f'[{x}, 0., 0., 0.]')+',\n'
s+=']} }\n}\n#[repr(C)]\n#[derive(Clone, Copy, bytemuck::Pod, bytemuck::Zeroable)]\npub struct GpuMaterial { pub values: [[f32;4]; '+str(len(fields)+1)+'] }\n'
Path('src/material/schema.rs').write_text(s)
s='// Generated material ABI v1. No BSDF dependency.\n#ifndef LAVA_MATERIAL_RECORD\n#define LAVA_MATERIAL_RECORD\nstruct MaterialRecord { vec4 values['+str(len(fields)+1)+']; };\nlayout(std430,set=0,binding=13) readonly buffer MaterialTable { MaterialRecord materials[]; };\n#endif\n'
Path('shaders/materials/record.glsl').write_text(s)
s='// Generated lowering from native material IR to the reference OpenPBR inputs.\n#extension GL_EXT_control_flow_attributes : require\n#include \"textures.glsl\"\nOpenPBR_ResolvedInputs materialInputs(uint id, vec3 normal, vec2 uv, float footprint) {\n MaterialRecord m=materials[id];\n [[dont_unroll]] for(uint field=1u;field<38u;field++) {if(textureSlots[id*40u+field].info.x!=0u)m.values[field]=materialValue(id,field,uv,footprint); }\n OpenPBR_ResolvedInputs p=openpbr_make_default_resolved_inputs();\n'
for i,(k,v) in enumerate(fields.items(),1):
 if k=='geometry_opacity':continue # coverage applied in visibility/ray traversal
 expression=f'm.values[{i}]'+('.xyz' if isinstance(v,tuple) else '.x!=0.' if isinstance(v,bool) else '.x')
 if not isinstance(v,bool):
  if k in ('base_weight','base_metalness','specular_roughness','specular_roughness_anisotropy','coat_weight','coat_roughness','coat_roughness_anisotropy','fuzz_weight','fuzz_roughness','transmission_weight','thin_film_weight'):expression=f'clamp({expression},0.,1.)'
  elif k.endswith('_ior'):expression=f'max(1.,{expression})'
  else:expression=f'max({expression},'+('vec3(0)' if isinstance(v,tuple) else '0.')+')'
 s+=f' p.{k}={expression};\n'
s+=' p.geometry_basis=openpbr_make_basis(normal);\n p.geometry_coat_basis=p.geometry_basis;\n return p;\n}\n'
Path('shaders/materials/inputs.glsl').write_text(s)
opacity=list(fields).index('geometry_opacity')+1
Path('shaders/materials/visibility.glsl').write_text("""#ifndef LAVA_MATERIAL_VISIBILITY
#define LAVA_MATERIAL_VISIBILITY
#include "record.glsl"
#include "textures.glsl"
uint materialId(uint primitive) {return floatBitsToUint(triangles[primitive].material.w);}
float materialCoverage(uint primitive,vec3 origin,vec3 direction) {
 uint id=materialId(primitive);
 if(materials[id].values[0].x==0.)return 1.;
 vec2 uv;float footprint;materialRayCoordinates(primitive,origin,direction,uv,footprint);
 return clamp(materialValue(id,31u,uv,footprint).x,0.,1.);
}
#include "coverage.glsl"
#endif
""")

s='// Generated by scripts/generate_material.py (native OpenPBR inputs).\n'
for k,v in fields.items():s+=f'LAVA_{"COLOR" if isinstance(v,tuple) else "BOOL" if isinstance(v,bool) else "FLOAT"}({k})\n'
Path('hydra/material_fields.inc').write_text(s)

lines=['#usda 1.0']
for ident in ['OpenPBRSurface','open_pbr_surface','ND_open_pbr_surface_surfaceshader']:
 lines += [f'def Shader "{ident}" {{','uniform token info:implementationSource = "sourceAsset"','uniform asset info:glslfx:sourceAsset = @lava_openpbr.glslfx@']
 for name,v in fields.items():
  typ='color3f' if isinstance(v,tuple) else 'bool' if isinstance(v,bool) else 'float'
  value='('+', '.join(map(str,v))+')' if isinstance(v,tuple) else str(v).lower()
  lines += [f'{typ} inputs:{name} = {value}']
 lines += ['token outputs:surface','}']
Path('hydra/openpbr_defs.usda').write_text('\n'.join(lines)+'\n')
Path('hydra/lava_openpbr.glslfx').write_text('-- glslfx version 0.1\n-- configuration\n{"techniques":{"default":{"surfaceShader":{"source":["Lava.Surface"]}}}}\n-- glsl Lava.Surface\n// Registry marker only. The Vulkan Material subsystem supplies the BSDF product.\n')

# Texture frontends share supported slot names and stable field IDs.
unsupported={'transmission_depth','transmission_scatter','transmission_scatter_anisotropy','transmission_dispersion_scale','transmission_dispersion_abbe_number','subsurface_weight','subsurface_color','subsurface_radius','subsurface_radius_scale','subsurface_scatter_anisotropy'}
rust='// Generated by scripts/generate_material.py.\npub fn texture_field(name:&str)->Option<(usize,bool)> {match name {\n'
cpp='// Generated texture-capable OpenPBR inputs.\n'
for i,(name,value) in enumerate(fields.items(),1):
 if isinstance(value,bool) or name in unsupported:continue
 color=str(isinstance(value,tuple)).lower()
 rust+=f'"{name}"=>Some(({i},{color})),\n'
 cpp+=f'LAVA_TEXTURE({name},{i},{color})\n'
rust+='\"normal\"=>Some((38,false)),\n\"bump\"=>Some((39,false)),\n_=>None,}}\n'
cpp+='LAVA_TEXTURE(normal,38,false)\nLAVA_TEXTURE(bump,39,false)\n'
Path('src/material/texture_fields.rs').write_text(rust)
Path('hydra/material_texture_fields.inc').write_text(cpp)
